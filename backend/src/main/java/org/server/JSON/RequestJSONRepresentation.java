package org.server.JSON;

public class RequestJSONRepresentation {
    private String tokensValue;
    private String stackValue;

    public String getTokensValue() {
        return tokensValue;
    }

    public void setTokensValue(String tokensValue) {
        this.tokensValue = tokensValue;
    }

    public String getStackValue() {
        return stackValue;
    }

    public void setStackValue(String stackValue) {
        this.stackValue = stackValue;
    }
}
